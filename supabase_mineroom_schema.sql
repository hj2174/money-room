-- ------------------------------------------------------------------------------
-- 1. 테이블 생성 (TABLES)
-- ------------------------------------------------------------------------------

-- 1-1. 방 메타데이터 테이블 (rooms) - points 기본값 0
CREATE TABLE IF NOT EXISTS public.rooms (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL DEFAULT '내 방',
    room_type TEXT NOT NULL DEFAULT 'personal' CHECK (room_type IN ('personal', 'shared')),
    tier TEXT NOT NULL DEFAULT 'studio' CHECK (tier IN ('studio', 'one_room_plus', 'penthouse')),
    points INTEGER NOT NULL DEFAULT 0 CHECK (points >= 0),
    converted_asset_amount BIGINT NOT NULL DEFAULT 0 CHECK (converted_asset_amount >= 0),
    wallpaper_id TEXT REFERENCES public.furniture_catalog(id) ON DELETE SET NULL,
    flooring_id TEXT REFERENCES public.furniture_catalog(id) ON DELETE SET NULL,
    window_id TEXT REFERENCES public.furniture_catalog(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 1-2. 방 멤버십 테이블 (room_members)
CREATE TABLE IF NOT EXISTS public.room_members (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    room_id UUID NOT NULL REFERENCES public.rooms(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    role TEXT NOT NULL DEFAULT 'owner' CHECK (role IN ('owner', 'member')),
    joined_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_room_members UNIQUE (room_id, user_id)
);

-- 1-3. 방 소유 가구 인벤토리 (room_inventory)
CREATE TABLE IF NOT EXISTS public.room_inventory (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    room_id UUID NOT NULL REFERENCES public.rooms(id) ON DELETE CASCADE,
    furniture_id TEXT NOT NULL REFERENCES public.furniture_catalog(id) ON DELETE CASCADE,
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_room_inventory UNIQUE (room_id, furniture_id)
);

-- 1-4. 방 배치 가구 인스턴스 (room_placed_items)
CREATE TABLE IF NOT EXISTS public.room_placed_items (
    id TEXT PRIMARY KEY,
    room_id UUID NOT NULL REFERENCES public.rooms(id) ON DELETE CASCADE,
    furniture_id TEXT NOT NULL REFERENCES public.furniture_catalog(id) ON DELETE CASCADE,
    x INTEGER NOT NULL,
    y INTEGER NOT NULL,
    rotation INTEGER NOT NULL DEFAULT 0 CHECK (rotation IN (0, 90, 180, 270)),
    flip_h BOOLEAN NOT NULL DEFAULT false,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 1-5. 포인트 감사 원장 테이블 (point_ledger)
CREATE TABLE IF NOT EXISTS public.point_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id UUID NOT NULL REFERENCES public.rooms(id) ON DELETE CASCADE,
    amount INTEGER NOT NULL,
    balance_after INTEGER NOT NULL CHECK (balance_after >= 0),
    reason TEXT NOT NULL,
    reference_amount BIGINT DEFAULT NULL,
    actor_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 1-6. 목표 달성 해금 기록 테이블 (room_unlocks)
CREATE TABLE IF NOT EXISTS public.room_unlocks (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    room_id UUID NOT NULL REFERENCES public.rooms(id) ON DELETE CASCADE,
    unlock_type TEXT NOT NULL CHECK (unlock_type IN ('FURNITURE', 'TIER', 'THEME')),
    target_id TEXT NOT NULL,
    source_goal_id TEXT DEFAULT NULL,
    unlocked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_room_unlocks UNIQUE (room_id, unlock_type, target_id)
);

