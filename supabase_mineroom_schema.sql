--   2. admin_grant_points 엄격한 관리자 인증:
--      - c_admin_user_id 상수 문자열('여기에-내-UUID') 설정
--      - 미설정(기본값)이거나 호출자 UUID와 불일치 시 무조건 거부 (방 소유자 우회 분기 전면 삭제)
--   3. 테이블 직접 쓰기 제한: rooms, room_inventory는 SELECT만 허용, 쓰기는 RPC 전용
--   4. 배치 유효성 트리거: room_placed_items는 room_id 변경 방지 및 [보유 수량 - 배치 개수 >= 1] 서버 검증
--   5. change_room_points 내부 전용화: 클라이언트(authenticated, anon) 직접 실행 불가
