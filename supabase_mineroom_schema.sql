-- 5-1. [내부 전용] 포인트 증감 및 원장 기록 공통 함수 (change_room_points)
-- ⚠️ 외부 권한 REVOKE 처리됨: 브라우저에서 직접 호출 불가
CREATE OR REPLACE FUNCTION public.change_room_points(
    p_room_id UUID,
    p_amount INTEGER,
    p_reason TEXT,
    p_ref_amount BIGINT DEFAULT NULL
)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_current_points INTEGER;
    v_new_points INTEGER;
    v_actor_id UUID := auth.uid();
BEGIN
    IF v_actor_id IS NULL THEN
        RAISE EXCEPTION 'UNAUTHORIZED: 로그인 세션이 필요합니다.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM public.room_members 
        WHERE room_id = p_room_id AND user_id = v_actor_id
    ) THEN
        RAISE EXCEPTION 'PERMISSION_DENIED: 해당 방의 포인트를 수정할 권한이 없습니다.';
    END IF;

    SELECT points INTO v_current_points
    FROM public.rooms
    WHERE id = p_room_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'ROOM_NOT_FOUND: 방을 찾을 수 없습니다. (ID: %)', p_room_id;
    END IF;

    v_new_points := v_current_points + p_amount;

    IF v_new_points < 0 THEN
        RAISE EXCEPTION 'INSUFFICIENT_POINTS: 보유 포인트가 부족합니다. (현재: %, 요청: %)', v_current_points, p_amount;
    END IF;

    UPDATE public.rooms
    SET points = v_new_points,
        updated_at = now()
    WHERE id = p_room_id;

    INSERT INTO public.point_ledger (
        room_id,
        amount,
        balance_after,
        reason,
        reference_amount,
        actor_id,
        created_at
    ) VALUES (
        p_room_id,
        p_amount,
        v_new_points,
        p_reason,
        p_ref_amount,
        v_actor_id,
        now()
    );

    RETURN v_new_points;
END;
$$;

-- change_room_points 내부 전용화: 직접 실행 권한 박탈
REVOKE ALL ON FUNCTION public.change_room_points(UUID, INTEGER, TEXT, BIGINT) FROM PUBLIC, anon, authenticated;

-- 5-2. [클라이언트 호출 RPC] 가구 구매 (purchase_furniture)
CREATE OR REPLACE FUNCTION public.purchase_furniture(
    p_room_id UUID,
    p_furniture_id TEXT,
    p_quantity INTEGER DEFAULT 1
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_actor_id UUID := auth.uid();
    v_price INTEGER;
    v_category TEXT;
    v_total_cost INTEGER;
    v_new_points INTEGER;
    v_new_qty INTEGER;
BEGIN
    IF v_actor_id IS NULL THEN RAISE EXCEPTION 'UNAUTHORIZED: 로그인 세션이 필요합니다.'; END IF;
    IF p_quantity IS NULL OR p_quantity <= 0 THEN RAISE EXCEPTION 'INVALID_QUANTITY: 구매 수량은 1개 이상이어야 합니다.'; END IF;
    IF NOT EXISTS (SELECT 1 FROM public.room_members WHERE room_id = p_room_id AND user_id = v_actor_id) THEN
        RAISE EXCEPTION 'PERMISSION_DENIED: 해당 방의 가구를 구매할 권한이 없습니다.';
    END IF;

    SELECT price, category INTO v_price, v_category
    FROM public.furniture_catalog
    WHERE id = p_furniture_id;

    IF NOT FOUND THEN RAISE EXCEPTION 'ITEM_NOT_FOUND: 존재하지 않는 가구 아이템입니다. (ID: %)', p_furniture_id; END IF;

    IF v_category IN ('wallpaper', 'flooring', 'window') THEN
        IF p_quantity > 1 THEN RAISE EXCEPTION 'BACKGROUND_SINGLE_ONLY: 배경 아이템은 한 번에 1개만 구매할 수 있습니다.'; END IF;
        IF EXISTS (
            SELECT 1 FROM public.room_inventory 
            WHERE room_id = p_room_id AND furniture_id = p_furniture_id AND quantity > 0
        ) THEN
            RAISE EXCEPTION 'ALREADY_OWNED: 이미 보유 중인 배경 아이템은 추가 구매할 수 없습니다.';
        END IF;
    END IF;

    v_total_cost := v_price * p_quantity;
    v_new_points := public.change_room_points(p_room_id, -v_total_cost, 'FURNITURE_PURCHASE', NULL);

    INSERT INTO public.room_inventory (room_id, furniture_id, quantity, created_at, updated_at)
    VALUES (p_room_id, p_furniture_id, p_quantity, now(), now())
    ON CONFLICT (room_id, furniture_id)
    DO UPDATE SET quantity = room_inventory.quantity + EXCLUDED.quantity, updated_at = now()
    RETURNING quantity INTO v_new_qty;

    RETURN jsonb_build_object(
        'success', true,
        'room_id', p_room_id,
        'furniture_id', p_furniture_id,
        'purchased_quantity', p_quantity,
        'total_inventory_quantity', v_new_qty,
        'cost', v_total_cost,
        'remaining_points', v_new_points
    );
END;
$$;

-- 5-3. [클라이언트 호출 RPC] 개인 방 생성 및 1,000P 지급 (create_personal_room)
CREATE OR REPLACE FUNCTION public.create_personal_room(
    p_name TEXT DEFAULT '내 방'
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_actor_id UUID := auth.uid();
    v_room_id UUID;
    v_existing_room RECORD;
    v_room_name TEXT;
    v_init_points INTEGER;
BEGIN
    IF v_actor_id IS NULL THEN RAISE EXCEPTION 'UNAUTHORIZED: 로그인 세션이 필요합니다.'; END IF;

    SELECT id, name, tier, points INTO v_existing_room
    FROM public.rooms
    WHERE owner_id = v_actor_id AND room_type = 'personal'
    LIMIT 1;

    IF FOUND THEN
        RETURN jsonb_build_object('success', true, 'is_new', false, 'room_id', v_existing_room.id, 'name', v_existing_room.name, 'points', v_existing_room.points);
    END IF;

    v_room_name := COALESCE(NULLIF(trim(p_name), ''), '내 방');

    INSERT INTO public.rooms (owner_id, name, room_type, tier, points, converted_asset_amount, created_at, updated_at)
    VALUES (v_actor_id, v_room_name, 'personal', 'studio', 0, 0, now(), now())
    RETURNING id INTO v_room_id;

    INSERT INTO public.room_members (room_id, user_id, role, joined_at)
    VALUES (v_room_id, v_actor_id, 'owner', now());

    v_init_points := public.change_room_points(v_room_id, 1000, 'INITIAL_GRANT', NULL);

    RETURN jsonb_build_object('success', true, 'is_new', true, 'room_id', v_room_id, 'name', v_room_name, 'points', v_init_points);
END;
$$;

-- 5-4. [클라이언트 호출 RPC] 테스트/관리자 포인트 지급 (admin_grant_points)
-- ⚠️ '여기에-내-UUID'에 본인의 Supabase auth.users(id)를 입력하세요.
-- 관리자 ID가 기본값이거나 호출자 UUID와 불일치 시 무조건 거부됩니다.
CREATE OR REPLACE FUNCTION public.admin_grant_points(
    p_room_id UUID,
    p_amount INTEGER,
    p_reason TEXT DEFAULT 'ADMIN_GRANT'
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_actor_id UUID := auth.uid();
    v_new_points INTEGER;
    -- 💡 본인의 Supabase auth.users(id) UUID를 작은따옴표 안에 입력하세요. (예: 'c8b417e2-...')
    c_admin_user_id CONSTANT TEXT := '여기에-내-UUID'; 
BEGIN
    -- 1. 로그인 세션 검증
    IF v_actor_id IS NULL THEN 
        RAISE EXCEPTION 'UNAUTHORIZED: 로그인 세션이 필요합니다.'; 
    END IF;

    -- 2. 관리자 ID 설정 여부 및 호출자 일치 검증 (불일치 시 무조건 거부)
    IF c_admin_user_id = '여기에-내-UUID' 
       OR c_admin_user_id IS NULL 
       OR trim(c_admin_user_id) = '' 
       OR v_actor_id::TEXT <> c_admin_user_id THEN
        RAISE EXCEPTION 'FORBIDDEN: 인가된 관리자 계정만 포인트를 지급할 수 있습니다. (SQL에서 c_admin_user_id를 먼저 설정하세요)';
    END IF;

    -- 3. 지급 금액 검증
    IF p_amount <= 0 THEN 
        RAISE EXCEPTION 'INVALID_AMOUNT: 지급할 포인트는 1P 이상이어야 합니다.'; 
    END IF;

    -- 4. 포인트 지급
    v_new_points := public.change_room_points(p_room_id, p_amount, COALESCE(p_reason, 'ADMIN_GRANT'), NULL);

    RETURN jsonb_build_object(
        'success', true, 
        'room_id', p_room_id, 
        'granted_amount', p_amount, 
        'balance_after', v_new_points
    );
END;
$$;

